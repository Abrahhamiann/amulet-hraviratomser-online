def normalize_language(language: str | None, fallback: str = "en") -> str:
    candidate = (language or "").split("-")[0].lower()
    return candidate if candidate in LANGUAGES else fallback


def tr(language: str, key: str, **values) -> str:
    template = TEXTS.get(language, TEXTS["en"]).get(key, TEXTS["en"].get(key, key))
    return template.format(**values)
